#!/usr/bin/env bash
# Portable scoring and Bracken reconstruction from the supplied original code.
set -euo pipefail
filter_id=$1
raw_kraken=$2
database=$3
output=$4
mkdir -p "$output"
kraken_score_filter.py 0.2 "$raw_kraken" "$output/retained.kraken.out" "$output/assignments.unsorted.tsv"
LC_ALL=C sort -t $'\t' -k1,1 -u "$output/assignments.unsorted.tsv" > "$output/retained_assignments.tsv"
rm "$output/assignments.unsorted.tsv"
build_kraken_report.py "$output/retained.kraken.out" "$database" "$output/bracken_input.report"
if [[ -s "$output/bracken_input.report" ]]; then
  bracken -d "$database" -i "$output/bracken_input.report" \
    -o "$output/bracken_species.tsv" -r 150 -l S -t 10
else
  printf 'name\ttaxonomy_id\ttaxonomy_lvl\tkraken_assigned_reads\tadded_reads\tnew_est_reads\tfraction_total_reads\n' > "$output/bracken_species.tsv"
fi
python - "$filter_id" "$output/provenance.json" <<'PY'
import json,sys
from pathlib import Path
Path(sys.argv[2]).write_text(json.dumps({
 'filter_id':sys.argv[1], 'score_threshold':0.2,
 'score_rule':'Assigned-taxid k-mers / nonzero nonambiguous k-mers; retain uncalculable scores',
 'source_scripts':['kraken2Filter.sh','bracken.sh'],
 'bracken':{'rank':'S','read_length':150,'minimum_reads':10},
 'rank_annotations':'Not generated by this adapter: requires the original frozen taxonomy dump',
 'note':'Kraken raw output must use --use-names for the original report builder'
},indent=2)+'\n')
PY
